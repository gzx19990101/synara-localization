let compressedRewriteCount = 0;

// 静态资源服务器按 brotli > gzip > 原文件的优先级返回内容
// （见 apps/server 的 negotiateStaticEncodingPreference），
// 只改 .js 不改 .br/.gz 的话，浏览器拿到的仍然是旧的英文资源。
function rewriteCompressedSiblings(filePath, content) {
  const buffer = Buffer.from(content, 'utf-8');
  const siblings = [
    ['.br', () => zlib.brotliCompressSync(buffer, {
      params: { [zlib.constants.BROTLI_PARAM_QUALITY]: 9 },
    })],
    ['.gz', () => zlib.gzipSync(buffer)],
  ];

  for (const [ext, compress] of siblings) {
    const siblingPath = filePath + ext;
    if (!fs.existsSync(siblingPath)) continue;
    fs.writeFileSync(siblingPath, compress());
    compressedRewriteCount++;
  }
}

function applyTranslations(filePath, translations) {
  if (!fs.existsSync(filePath)) {
    console.log(`  跳过（文件不存在）: ${path.basename(filePath)}`);
    return 0;
  }

  let content = fs.readFileSync(filePath, 'utf-8');
  let count = 0;

  for (const [from, to] of Object.entries(translations)) {
    if (content.includes(from)) {
      // 使用 split/join 进行全局替换（避免正则特殊字符问题）
      const parts = content.split(from);
      count += parts.length - 1;
      content = parts.join(to);
    }
  }

  if (count > 0) {
    fs.writeFileSync(filePath, content, 'utf-8');
    rewriteCompressedSiblings(filePath, content);
  }
  return count;
}

function findFileByPattern(dir, pattern) {
  if (!fs.existsSync(dir)) return null;
  const files = fs.readdirSync(dir);
  const regex = new RegExp(pattern);
  const found = files.find(f => regex.test(f));
  return found ? path.join(dir, found) : null;
}

